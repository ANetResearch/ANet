#!/usr/bin/env python3
"""Build the ZCode marketplace of anet.

    python3 deploy/zcode/build.py --out DIR [--base URL]

The plugin itself is generated by deploy/plugins (target zcode); this script
writes the static tree that publish.sh --zcode puts under /zcode/ on
agentnetwork.org.cn:

    DIR/marketplace.json
    DIR/assets/anet/icon.png
    DIR/plugins/anet/<version>/plugin.zip

The archive is reproducible, and its SHA-256 is written into the marketplace
entry, which ZCode checks. It is the same output as

    python3 deploy/plugins/build.py --target zcode --site SITE

below SITE/zcode/. Nothing is written when a check fails.
"""

import argparse
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "plugins"))

import generator as g  # noqa: E402

BASE = "https://agentnetwork.org.cn/zcode"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--base", default=BASE, help="public URL of the /zcode/ directory (default %(default)s)")
    args = parser.parse_args()
    try:
        ctx = g.build_all(["zcode"]).contexts["zcode"]
        site = g.Site(ctx, args.base)
        ctx.module.site(ctx, site)
        g.write_tree(site.files, args.out, force=True)
    except (g.BuildError, ValueError) as e:
        print(f"build.py: {e}", file=sys.stderr)
        return 1
    name, version = ctx.meta["name"], ctx.meta["version"]
    data = site.files[f"plugins/{name}/{version}/plugin.zip"].data
    print(f"{name} {version}: plugins/{name}/{version}/plugin.zip sha256 {g.sha256_hex(data)} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
