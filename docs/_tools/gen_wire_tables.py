#!/usr/bin/env python3
"""Generate the wire tables of the reference from ANetCore/wire/registry.json.

    python3 docs/_tools/gen_wire_tables.py --registry /path/to/ANetCore/wire/registry.json

Writes into docs/reference/_generated/:

  hub-headers.inc      HTTP headers of the hub API
  hub-endpoints.inc    the endpoints of the hub API that the registry lists
  relayauth-actions.inc  the relayauth actions
  protocol-labels.inc  domain-separation labels and type tags
  protocol-objects.inc key tables of the main wire objects

The registry is the machine-readable register of everything that anet 0.3.0
puts on the wire; ANetCore/docs/wire-keys.md is generated from the same file.
The output files are committed; rerun the script when the registry changes.
"""
import argparse
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "reference" / "_generated"

OBJECTS = ["SealedEnvelope", "Access", "Cap", "CapBody", "Wrap", "SealedInner", "Grant",
           "EncKeySet", "EncKey", "Mbox", "SignedEncKeySet", "KeyEvent", "SignedEvent",
           "NoticeBody", "NoticeWire", "DirEntry"]

ESC = re.compile(r"([\\*`|])")


def esc(s):
    s = str(s)
    s = ESC.sub(r"\\\1", s)
    s = re.sub(r"(\w)_(?=\s|$|[.,;:)])", r"\1\\_", s)
    # a leading angle bracket expression such as <Access> is plain text in rst
    return s


def lit(s):
    return "``%s``" % str(s).replace("`", "'")


def table(header, widths, rows, out):
    out.append(".. list-table::")
    out.append("   :header-rows: 1")
    out.append("   :widths: %s" % " ".join(str(w) for w in widths))
    out.append("")
    out.append("   * - " + header[0])
    for h in header[1:]:
        out.append("     - " + h)
    for r in rows:
        out.append("   * - " + r[0])
        for c in r[1:]:
            out.append("     - " + (c if c else ""))
    out.append("")


def fields_text(fields, indent=""):
    """Names of the members of a request or response, nested ones in parentheses."""
    parts = []
    for f in fields or []:
        t = lit(f["name"]) + ("" if f.get("req") == "must" else "?")
        if f.get("fields"):
            t += " [" + fields_text(f["fields"]) + "]"
        parts.append(t)
    return ", ".join(parts)


def endpoint_rows(reg, fed):
    rows = []
    for e in reg["hub_api"]["endpoints"]:
        if e["path"].startswith("/fed/") != fed:
            continue
        req = e.get("request") or {}
        resp = e.get("response") or {}
        reqt = req.get("raw") or fields_text(req.get("fields"))
        respt = resp.get("raw") or fields_text(resp.get("fields"))
        reasons = ", ".join(lit(r) for r in e.get("reasons") or [])
        rows.append([lit("%s %s" % (e["method"], e["path"])), esc(e["auth"]),
                     reqt if req.get("raw") is None else esc(reqt), respt if resp.get("raw") is None else esc(respt),
                     reasons])
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--registry", required=True)
    args = ap.parse_args()
    reg = json.load(open(args.registry, encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    banner = [".. Generated by docs/_tools/gen_wire_tables.py from wire/registry.json (ANetCore).",
              ".. Do not edit by hand; rerun the script when the registry changes.", ""]

    # headers
    out = list(banner)
    rows = [[lit(h["name"]), esc(h["dir"]), esc(h["where"]), esc(h["value"])] for h in reg["hub_api"]["headers"]]
    table(["Header", "Direction", "Where", "Value"], [20, 14, 26, 40], rows, out)
    (OUT / "hub-headers.inc").write_text("\n".join(out), encoding="utf-8")

    # endpoints (hub and federation)
    for name, fed in (("hub-endpoints.inc", False), ("hub-fed-endpoints.inc", True)):
        out = list(banner)
        table(["Endpoint", "Authentication", "Request members", "Response members", "Route-specific codes"],
              [20, 16, 22, 28, 14], endpoint_rows(reg, fed), out)
        (OUT / name).write_text("\n".join(out), encoding="utf-8")

    # removed routes
    out = list(banner)
    for r in reg["hub_api"]["removed"]:
        out.append("* " + esc(r))
    out.append("")
    (OUT / "hub-removed.inc").write_text("\n".join(out), encoding="utf-8")

    # relayauth actions
    out = list(banner)
    rows = [[lit(a["name"]), lit(a["route"]) if a["route"] != "-" else "", esc(a["signer"]), esc(a["status"])]
            for a in reg["relayauth"]["actions"]]
    table(["Action", "Route", "Signer", "Status"], [18, 38, 22, 22], rows, out)
    (OUT / "relayauth-actions.inc").write_text("\n".join(out), encoding="utf-8")

    # labels
    out = list(banner)
    rows = []
    for t in reg["tags"]:
        rows.append([esc(t["id"]), "; ".join(lit(v) for v in t["values"]), esc(t["class"]), esc(t["build"]),
                     esc(t["key"])])
    table(["Id", "Label or tag", "Class", "Construction", "Key"], [6, 22, 8, 46, 18], rows, out)
    (OUT / "protocol-labels.inc").write_text("\n".join(out), encoding="utf-8")

    # objects
    out = list(banner)
    byname = {o["name"]: o for o in reg["objects"]}
    for n in OBJECTS:
        o = byname[n]
        out.append(".. _wire-object-%s:" % n.lower())
        out.append("")
        out.append(n)
        out.append("~" * len(n))
        out.append("")
        out.append(esc(o["desc"]))
        extra = []
        if o.get("tag"):
            extra.append("Type tag %s." % lit(o["tag"]))
        extra.append("Key space: %s." % {"closed": "closed, every unregistered key is refused",
                                           "critical": "keys 0 to 63 must be understood, keys from 64 are kept and covered by digests"}.get(o["keyspace"], o["keyspace"]))
        out.append("")
        out.append(" ".join(extra))
        out.append("")
        rows = []
        for k in o["keys"]:
            num = str(k["n"]) + (" to %d" % k["to"] if k.get("to") else "")
            if k["status"] != "active" and not k.get("name"):
                label = {"reserved": "reserved", "retired": "retired", "forbidden": "forbidden"}[k["status"]]
                note = esc(k.get("note", ""))
                if k.get("was"):
                    note = ("was " + lit(k["was"]) + ". " + note).strip()
                rows.append([num, "", "", label, note])
                continue
            typ = k["type"] + (" (%d bytes)" % k["size"] if k.get("size") else "")
            if k.get("value") is not None:
                typ += " = " + k["value"]
            req = {"must": "required", "may": "optional", "cond": "conditional"}.get(k.get("req"), "")
            note = esc(k.get("note", ""))
            if k.get("cond"):
                note = ("%s. %s" % (esc(k["cond"]), note)).strip()
            rows.append([num, lit(k["name"]), esc(typ), req, note])
        table(["Key", "Name", "Type", "Presence", "Notes"], [8, 14, 22, 12, 44], rows, out)
    (OUT / "protocol-objects.inc").write_text("\n".join(out), encoding="utf-8")
    print("wrote tables into %s" % OUT)


if __name__ == "__main__":
    main()
