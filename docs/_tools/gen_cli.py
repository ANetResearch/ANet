#!/usr/bin/env python3
"""Generate reference/_generated/cli-commands.inc from the output of `anet help --all`.

    python3 docs/_tools/gen_cli.py --anet /path/to/anet

The binary is run with ANET_LANG=en so that the English help is printed. The output
file is committed; rerun the script when the command tree changes.
"""
import argparse
import os
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "reference" / "_generated" / "cli-commands.inc"

ENTRY = re.compile(r"^  (anet .+?)\s{2,}(\S.*)$")
ESC = re.compile(r"([\\*`|])")


FLAG = re.compile(r"(?<![\w`-])(--[a-z][a-z0-9-]*|anet [a-z][a-z-]*)")


def esc(s):
    marks = []

    def hold(m):
        marks.append("``%s``" % m.group(1))
        return "\x00%d\x00" % (len(marks) - 1)

    s = FLAG.sub(hold, s)
    s = ESC.sub(r"\\\1", s)
    s = re.sub(r"(\w)_(?=\s|$)", r"\1\\_", s)
    return re.sub(r"\x00(\d+)\x00", lambda m: marks[int(m.group(1))], s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--anet", default="anet")
    args = ap.parse_args()
    env = dict(os.environ, ANET_LANG="en")
    env.pop("LC_MESSAGES", None)
    text = subprocess.run([args.anet, "help", "--all"], check=True, capture_output=True,
                          text=True, env=env).stdout
    sections = []
    for line in text.splitlines()[1:]:
        if not line.strip():
            continue
        if not line.startswith(" "):
            sections.append((line.strip(), []))
            continue
        m = ENTRY.match(line)
        if not m:
            print("unparsed line: %r" % line, file=sys.stderr)
            sys.exit(1)
        sections[-1][1].append((m.group(1), m.group(2)))
    out = [".. Generated by docs/_tools/gen_cli.py from `anet help --all`.",
           ".. Do not edit by hand; rerun the script when the command tree changes.", ""]
    for title, entries in sections:
        out += [title, "~" * len(title), "", ".. list-table::", "   :header-rows: 1",
                "   :widths: 45 55", "", "   * - Invocation", "     - Description"]
        for use, desc in entries:
            out.append("   * - ``%s``" % use)
            out.append("     - %s" % esc(desc))
        out.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print("wrote %s (%d sections)" % (OUT, len(sections)))


if __name__ == "__main__":
    main()
