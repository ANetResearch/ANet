#!/usr/bin/env python3
"""Generate reference/_generated/hub-reasons.inc from the hub reason table.

    python3 docs/_tools/gen_hub_reasons.py --hub-reasons /path/to/ANetHub/internal/wire3/reasons.go

The table is the map `reasons` of internal/wire3/reasons.go in the ANetHub
repository: every reason code a hub returns, with its HTTP status, the extra
members of the body and the default English sentence. The output file is
committed; rerun the script when the table changes.
"""
import argparse
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "reference" / "_generated" / "hub-reasons.inc"

STATUS = {
    "StatusUpgradeRequired": 426, "StatusBadRequest": 400, "StatusNotFound": 404,
    "StatusRequestEntityTooLarge": 413, "StatusInternalServerError": 500,
    "StatusUnauthorized": 401, "StatusForbidden": 403, "StatusConflict": 409,
    "StatusTooManyRequests": 429, "StatusInsufficientStorage": 507,
    "StatusBadGateway": 502, "StatusGone": 410, "StatusServiceUnavailable": 503,
}
ESC = re.compile(r"([\\*`|])")


def esc(s):
    s = ESC.sub(r"\\\1", s)
    return re.sub(r"(\w)_(?=\s|$|[.,;:)])", r"\1\\_", s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hub-reasons", required=True)
    args = ap.parse_args()
    src = pathlib.Path(args.hub_reasons).read_text(encoding="utf-8")
    consts = dict(re.findall(r'(Reason\w+)\s+Reason\s*=\s*"([a-z_0-9]+)"', src))
    body = src[src.index("var reasons = map[Reason]reasonInfo{"):]
    rows = []
    for m in re.finditer(r'\t(Reason\w+): \{http\.(\w+), (nil|\[\]string\{([^}]*)\}),\s*\n\s*"((?:[^"\\]|\\.)*)"\}', body):
        name, st, _, extra, sentence = m.groups()
        extra = ", ".join(x.strip().strip('"') for x in (extra or "").split(",") if x.strip())
        rows.append((consts[name], STATUS[st], extra, sentence.replace('\\"', '"')))
    rows.sort()
    out = [".. Generated by docs/_tools/gen_hub_reasons.py from internal/wire3/reasons.go (ANetHub).",
           ".. Do not edit by hand; rerun the script when the table changes.", "",
           ".. list-table::", "   :header-rows: 1", "   :widths: 22 8 16 54", "",
           "   * - Code", "     - Status", "     - Extra members", "     - Default sentence"]
    for code, st, extra, sentence in rows:
        out.append("   * - ``%s``" % code)
        out.append("     - %d" % st)
        out.append("     - %s" % ("".join("``%s`` " % e.strip() for e in extra.split(",")) if extra else ""))
        out.append("     - %s" % esc(sentence))
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote %s (%d codes)" % (OUT, len(rows)))


if __name__ == "__main__":
    main()
