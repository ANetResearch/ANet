#!/usr/bin/env python3
"""Generate reference/_generated/hub-reasons.inc from the hub reason table.

    python3 docs/_tools/gen_hub_reasons.py --hub-reasons /path/to/ANetHub/internal/wire3/reasons.go \\
        --hub-codes /path/to/ANetHub/internal/wire3/codes.txt

The table is the map `reasons` of internal/wire3/reasons.go in the ANetHub
repository: every reason code a hub returns, with its HTTP status, the extra
members of the body and the default English sentence. The output file is
committed; rerun the script when the table changes. The Since column and the
table of retired codes come from codes.txt of the same directory, the register
of every code the hub ever published.
"""
import argparse
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "reference" / "_generated" / "hub-reasons.inc"

STATUS = {
    "StatusUpgradeRequired": 426, "StatusBadRequest": 400, "StatusNotFound": 404,
    "StatusRequestEntityTooLarge": 413, "StatusInternalServerError": 500,
    "StatusUnauthorized": 401, "StatusForbidden": 403, "StatusConflict": 409,
    "StatusTooManyRequests": 429, "StatusInsufficientStorage": 507,
    "StatusBadGateway": 502, "StatusGone": 410, "StatusServiceUnavailable": 503,
}
ESC = re.compile(r"([\\*`|])")


def esc(s):
    s = ESC.sub(r"\\\1", s)
    return re.sub(r"(\w)_(?=\s|$|[.,;:)])", r"\1\\_", s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hub-reasons", required=True)
    ap.add_argument("--hub-codes", required=True)
    args = ap.parse_args()
    src = pathlib.Path(args.hub_reasons).read_text(encoding="utf-8")
    consts = dict(re.findall(r'(Reason\w+)\s+Reason\s*=\s*"([a-z_0-9]+)"', src))
    body = src[src.index("var reasons = map[Reason]reasonInfo{"):]
    rows = []
    for m in re.finditer(r'\t(Reason\w+): \{http\.(\w+), (nil|\[\]string\{([^}]*)\}),\s*\n\s*"((?:[^"\\]|\\.)*)"\}', body):
        name, st, _, extra, sentence = m.groups()
        extra = ", ".join(x.strip().strip('"') for x in (extra or "").split(",") if x.strip())
        rows.append((consts[name], STATUS[st], extra, sentence.replace('\\"', '"')))
    rows.sort()
    codes = {}
    for line in pathlib.Path(args.hub_codes).read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            f = line.rstrip().split("\t") + ["", ""]
            codes[f[0]] = f
    table = {r[0] for r in rows}
    for c, f in codes.items():
        if f[2] == "active" and c not in table:
            raise SystemExit("codes.txt lists %s as active and the table has no entry for it" % c)
    for c in table:
        if c not in codes or codes[c][2] != "active":
            raise SystemExit("the table has %s and codes.txt does not list it as active" % c)
    out = [".. Generated by docs/_tools/gen_hub_reasons.py from internal/wire3/reasons.go (ANetHub).",
           ".. Do not edit by hand; rerun the script when the table changes.", "",
           ".. list-table::", "   :header-rows: 1", "   :widths: 21 8 8 16 47", "",
           "   * - Code", "     - Since", "     - Status", "     - Extra members", "     - Default sentence"]
    for code, st, extra, sentence in rows:
        out.append("   * - .. _hub-reason-%s:" % code.replace("_", "-"))
        out.append("")
        out.append("       ``%s``" % code)
        out.append("     - %s" % codes[code][1])
        out.append("     - %d" % st)
        out.append("     - %s" % ("".join("``%s`` " % e.strip() for e in extra.split(",")) if extra else ""))
        out.append("     - %s" % esc(sentence))
    retired = sorted(c for c, f in codes.items() if f[2] == "retired")
    out += ["", ".. _hub-reasons-retired:", "", "Retired hub codes", "~~~~~~~~~~~~~~~~~", ""]
    if not retired:
        out += ["No hub code has been retired. A retired code stays on this list, with the version that",
                "retired it, and is never used again.", ""]
    else:
        out += ["A retired code is no longer returned. It stays on this list and is never used again.", "",
                ".. list-table::", "   :header-rows: 1", "   :widths: 25 15 15 45", "",
                "   * - Code", "     - Since", "     - Retired", "     - Replacement"]
        for c in retired:
            f = codes[c]
            out += ["   * - ``%s``" % c, "     - %s" % f[1], "     - %s" % f[3],
                    "     - %s" % ("``%s``" % f[4] if f[4] else "")]
        out.append("")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote %s (%d codes)" % (OUT, len(rows)))


if __name__ == "__main__":
    main()
