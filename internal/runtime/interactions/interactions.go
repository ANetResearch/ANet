// Package interactions is the daemon's task store: a single durable log of the delegation
// interactions this daemon is part of, in EITHER role. It is what lets an agent be only intermittently
// online — the daemon persists inbound tasks (so a provider whose external agent is offline still
// accepts and stores work) and outbound delegations (so a requester can read the result later), and
// both survive daemon restarts. Each interaction carries a multi-turn conversation (the message table).
//
// One SQLite table (+ a per-interaction message log), one row per interaction, discriminated by role:
//   - RoleInbound  — someone delegated a task TO us; we are the provider. The provider completes a
//     text task on its own (A2A-DESIGN §4.2) and signs a receipt over the transcript. anet itself
//     runs no model — the deliverable comes from the operator's EXTERNAL agent.
//   - RoleOutbound — WE delegated a task to a provider; we are the requester. We converse, then
//     receive the result + the provider's receipt and may attach our signed review.
//
// The task state (A2A-DESIGN §4.1) is written by the event that causes it, never derived from the
// conversation: every write goes through a guarded UPDATE that refuses to leave a terminal state,
// and increments state_seq so a waiter can tell a new state event from the value it already saw.
//
// interaction_id is generated by the REQUESTER at delegate time and carried on the wire, so both
// daemons key the same interaction by the same id — that shared id is what the receipt and the review
// bind to.
package interactions

