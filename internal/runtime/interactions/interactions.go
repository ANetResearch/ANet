// ErrBadInput is returned for missing required fields.
var ErrBadInput = errors.New("interactions: invalid input")

// ErrNotFound is returned when no interaction has the given id.
var ErrNotFound = errors.New("interactions: not found")

// ErrTerminal is returned by a state write against an interaction that is
// already in a terminal state. The row is left unchanged: a completed task
// is not canceled afterwards, a canceled one is not completed, and a
// receipt is never stored on a canceled interaction.
var ErrTerminal = errors.New("interactions: interaction is in a terminal state")

// Role is this daemon's side of an interaction.
type Role string

const (
	RoleInbound  Role = "inbound"  // someone delegated to us (we are the provider)
	RoleOutbound Role = "outbound" // we delegated to a provider (we are the requester)
)

// State is an interaction's task state (A2A-DESIGN §4.1). The strings are
// the A2A TaskState names in lowercase-hyphen form.
type State string

const (
	StateSubmitted     State = "submitted"
	StateWorking       State = "working"
	StateInputRequired State = "input-required"
	StateCompleted     State = "completed"
	StateFailed        State = "failed"
	StateCanceled      State = "canceled"
	StateRejected      State = "rejected"
)

// terminalSQL is the SQL list of terminal states. It is the only place the
// guarded writes name them; IsTerminal is its Go counterpart and a test
// keeps the two equal.
const terminalSQL = `('completed','failed','canceled','rejected')`

// IsTerminal reports whether s is one of the four terminal states. Every
// "has this task ended" check in the daemon goes through it.
func (s State) IsTerminal() bool {
	switch s {
	case StateCompleted, StateFailed, StateCanceled, StateRejected:
		return true
	}
	return false
}

// Valid reports whether s is one of the seven defined states.
func (s State) Valid() bool {
	switch s {
	case StateSubmitted, StateWorking, StateInputRequired,
		StateCompleted, StateFailed, StateCanceled, StateRejected:
		return true
	}
	return false
}

// Trust is how an inbound interaction was admitted (A2A-DESIGN §5.2). It is
// empty for an outbound interaction.
const (
	TrustPeer      = "peer"       // the requester is on the allow (or trust) list
	TrustPublic    = "public"     // a natural-language task accepted under the open policy
	TrustPublicCap = "public_cap" // a call to one of this node's public capabilities
	TrustApproved  = "approved"   // held in the pending queue and approved by the operator
)

// Values of the pay_state column (A2A-DESIGN §4.1). Written by the payment
// flow; listed here so the value domain is defined next to the column.
const (
	PayNone      = ""          // no quote
	PayRequired  = "required"  // quoted (provider) or quote received (requester)
	PaySubmitted = "submitted" // provider: payload persisted, awaiting settlement; requester: payment-submitted sent
	PayCompleted = "completed" // settled
	PayFailed    = "failed"    // settlement definitely failed
	PayRejected  = "rejected"  // the requester declined to pay
)

// Message kinds carried in the per-interaction conversation log.
const (
	MsgText       = "text"        // a normal chat message
	MsgEndRequest = "end_request" // the requester asks the provider to complete the task
	// MsgEndAccept is a historical kind. From wire 2 the provider completes on its own and no
	// daemon sends it; rows written before the change keep it.
	MsgEndAccept = "end_accept"
	MsgCancel    = "cancel"  // a cancellation request
	MsgStatus    = "status"  // a provider status update (anet.status/1)
	MsgPayment   = "payment" // an x402 payment message; only its metadata is stored
)

// Message is one entry in an interaction's conversation log. The sealed envelope it arrived in
// was signed by its sender (A2A-DESIGN §3.3); the log itself stores no signature.
type Message struct {
	Seq           int64
	InteractionID string
	SenderAID     string
	Kind          string // MsgText | MsgEndRequest | MsgCancel | MsgStatus | MsgPayment | MsgEndAccept
	Body          string
	// MsgID is the sender-minted message id. The sender stores its own id too, so both sides can
	// replay a history with message ids (A2A Message.messageId).
	MsgID string
	// Metadata is the message's JSON metadata object, or empty.
	Metadata  string
	CreatedAt string
}

// Attachment is one binary payload (image / media / archive) attached to a conversation message. The
// bytes are stored inline in SQLite (v0.1); integrity is pinned by CID = anetcid.SumRaw(Data). List/read
// helpers return metadata WITHOUT Data unless a data-loading accessor is used, to keep thread rendering
// and transcript building cheap.
type Attachment struct {
	Seq           int64
	InteractionID string
	MsgSeq        int64 // the message (message.seq) this attachment belongs to
	Name          string
	Mime          string
	Size          int64
	CID           string
	Data          []byte // populated only by AttachmentData
	CreatedAt     string
}

// Interaction is one stored delegation record.
type Interaction struct {
	Seq        int64  // local monotonic cursor
	ID         string // shared interaction_id (requester-generated)
	Role       Role
	PeerAID    string // the OTHER party: provider (outbound) or requester (inbound)
	Goal       string // the task text (for a public capability call: the capability id)
	State      State
	StateAt    int64 // unix ms of the last state write
	StateSeq   int64 // incremented by every state write
	RequestCID string
	RequestDoc []byte // the signed request TaskDoc bytes (Sum == RequestCID)
	ResultCID  string
	Result     []byte // the deliverable/transcript bytes
	Receipt    []byte // provider-signed receipt object (evidence.Receipt.Marshal)
	Review     []byte // requester-signed review object (evidence.Review.Marshal), outbound only
	// ReceiptVerified says whether this node could check the receipt that
	// came with the result: Verified, Unverified, or Unknown for a row
	// written before this was recorded. Three states, not two — a
	// completion nobody could audit is not the same as one that failed
	// an audit, and neither is the same as one that passed.
	ReceiptVerified Verification
	EndReqBy        string // historical: AID that requested ending ("" = none)
	EndAccBy        string // historical: AID that accepted (wire 1 only)
	ContextID       string
	Trust           string // TrustPeer | TrustPublic | TrustPublicCap | TrustApproved; "" for outbound
	IsCapability    bool
	TaskNonce       string // base64url of the TaskDoc's anet.nonce context
	PayState        string
	PayRequired     []byte // x402 PaymentRequired JSON
	PayAuthIDs      []string
	PayPayload      []byte
	PayReceipts     []byte // JSON array of settlement responses
	QuoteExpiresAt  int64  // unix ms
	// PeerKEL and PeerKeys hold the requester's KEL and SignedEncKeySet for
	// a public or public_cap interaction, whose peer is not recorded in
	// peer_identity (A2A-DESIGN §3.8). They are deleted when the
	// interaction reaches a terminal state.
	PeerKEL   []byte
	PeerKeys  []byte
	CreatedAt string // RFC3339Nano
	UpdatedAt string // RFC3339Nano

	// ResultMeta is the metadata object the result carried (anet.reason,
	// anet.retry_after_ms, anet.effect_status, x402 keys), as JSON, or "".
	// The deliverable is what the receipt covers; this is what the result
	// said about it, kept so a later reader — the A2A projection — can
	// still say why a task was refused and when to retry.
	ResultMeta string
}

// IsTerminal reports whether the interaction's state is terminal.
func (ix *Interaction) IsTerminal() bool { return ix != nil && ix.State.IsTerminal() }

// Verification is the three-state answer to "could this node check the
// receipt?". The zero value is Unknown on purpose: a row that predates
// this column, or any path that forgets to say, reads as "we do not
// know" rather than as either verdict.
type Verification string

const (
	VerificationUnknown    Verification = ""
	VerificationVerified   Verification = "verified"
	VerificationUnverified Verification = "unverified"
)

// Store is the daemon's interaction log.
type Store struct {
	db *sql.DB
	mu sync.Mutex // serializes writes (single writer); reads run lock-free under WAL
	// peerCap bounds the unpinned peer_identity rows (see peers.go).
	peerCap int
	// refusedCaps bounds the refused table; refusedRows counts its rows
	// once refusedCounted (see refused.go). Both under mu.
	refusedCaps    RefusedCaps
	refusedRows    int
	refusedCounted bool
	// now is the clock for state_at; tests replace it.
	now func() int64
}

// Open opens (creating if needed) an interactions store at dir (SQLite at dir/interactions.db).
func Open(dir string) (*Store, error) {
	if dir == "" {
		return nil, fmt.Errorf("interactions: dir required")
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return nil, fmt.Errorf("interactions: mkdir: %w", err)
	}
	db, err := sql.Open("sqlite", filepath.Join(dir, "interactions.db")+"?_pragma=journal_mode(WAL)&_pragma=synchronous(NORMAL)&_pragma=busy_timeout(15000)")
	if err != nil {
		return nil, fmt.Errorf("interactions: open db: %w", err)
	}
	s := &Store{db: db}
	if err := s.migrate(); err != nil {
		db.Close()
		return nil, err
	}
	return s, nil
}

// Close closes the db handle.
func (s *Store) Close() error { return s.db.Close() }

// SetClock replaces the clock used for state_at (unix ms). Tests only.
func (s *Store) SetClock(now func() int64) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.now = now
}

func (s *Store) nowMS() int64 {
	if s.now != nil {
		return s.now()
	}
	return time.Now().UnixMilli()
}

