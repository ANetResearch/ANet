// List returns interactions in the given role with seq > sinceSeq, oldest first. If state is non-empty
// it filters to that state. limit ≤ 0 → 100. It is the seq-cursor scan used by callers that page
// through a whole role; listings shown to a person use ListPage, which is newest first.
func (s *Store) List(role Role, state State, sinceSeq int64, limit int) ([]*Interaction, error) {
	if limit <= 0 {
		limit = 100
	}
	q := `SELECT ` + ixColumns + ` FROM interaction WHERE role=? AND seq > ?`
	args := []any{string(role), sinceSeq}
	if state != "" {
		q += ` AND state=?`
		args = append(args, string(state))
	}
	q += ` ORDER BY seq LIMIT ?`
	args = append(args, limit)
	return s.query(q, args...)
}

// ListFilter selects interactions for ListPage and Count.
type ListFilter struct {
	Role   Role    // "" = both roles
	States []State // empty = any state
	// Active selects non-terminal interactions only.
	Active bool
	// ExcludeTrust leaves out interactions with these trust values.
	ExcludeTrust []string
	// ExcludeCapability leaves out capability-call interactions.
	ExcludeCapability bool
	ContextID         string
	PeerAID           string
	// UpdatedAfter selects interactions whose state_at is after this unix ms (0 = no bound).
	UpdatedAfter int64
	// HasReceipt selects interactions that carry a receipt.
	HasReceipt bool
	// Cursor is the Next value of the previous page; empty starts at the newest.
	Cursor string
	// Limit bounds the page; ≤ 0 means 100, and it is capped at 1000.
	Limit int
}

// Page is one page of ListPage. Next is empty on the last page.
type Page struct {
	Items []*Interaction
	Next  string
}

func (f ListFilter) where() (string, []any, error) {
	var conds []string
	var args []any
	if f.Role != "" {
		conds = append(conds, `role=?`)
		args = append(args, string(f.Role))
	}
	if len(f.States) > 0 {
		ph := make([]string, len(f.States))
		for i, st := range f.States {
			ph[i] = "?"
			args = append(args, string(st))
		}
		conds = append(conds, `state IN (`+strings.Join(ph, ",")+`)`)
	}
	if f.Active {
		conds = append(conds, `state NOT IN `+terminalSQL)
	}
	for _, t := range f.ExcludeTrust {
		conds = append(conds, `trust != ?`)
		args = append(args, t)
	}
	if f.ExcludeCapability {
		conds = append(conds, `is_capability = 0`)
	}
	if f.ContextID != "" {
		conds = append(conds, `context_id=?`)
		args = append(args, f.ContextID)
	}
	if f.PeerAID != "" {
		conds = append(conds, `peer_aid=?`)
		args = append(args, f.PeerAID)
	}
	if f.UpdatedAfter > 0 {
		conds = append(conds, `state_at > ?`)
		args = append(args, f.UpdatedAfter)
	}
	if f.HasReceipt {
		conds = append(conds, `receipt IS NOT NULL AND length(receipt) > 0`)
	}
	if f.Cursor != "" {
		at, seq, err := parseCursor(f.Cursor)
		if err != nil {
			return "", nil, err
		}
		// A row value, not "state_at < ? OR (state_at = ? AND seq < ?)":
		// SQLite reads it as one range of the listing index, in order.
		conds = append(conds, `(state_at, seq) < (?, ?)`)
		args = append(args, at, seq)
	}
	if len(conds) == 0 {
		return "", args, nil
	}
	return ` WHERE ` + strings.Join(conds, " AND "), args, nil
}

// ListPage returns interactions matching f, most recent state change first
// (A2A ListTasks order), one page at a time. The cursor is the (state_at,
// seq) of the last item, so a page boundary is stable while rows are added
// at the head.
//
// A page is read in two steps: the (state_at, seq) of its rows from an index
// (pageSQL), then those rows whole (rowsBySeq). The page boundary — whether
// there is a next page, and the cursor — is the first step's. Taken from the
// rows re-read in the second, a task that changed state in between moved
// the cursor to the head of the listing (the next page repeated this one),
// and a task deleted in between (PruneTerminal) left a full page looking like
// the last one, so the rest of the listing was never read.
func (s *Store) ListPage(f ListFilter) (Page, error) {
	limit := f.Limit
	if limit <= 0 {
		limit = 100
	}
	if limit > 1000 {
		limit = 1000
	}
	q, args, err := f.pageSQL(limit + 1)
	if err != nil {
		return Page{}, err
	}
	keys, err := s.pageKeys(q, args)
	if err != nil {
		return Page{}, err
	}
	var p Page
	if len(keys) > limit {
		keys = keys[:limit]
		last := keys[limit-1]
		p.Next = strconv.FormatInt(last.at, 10) + "." + strconv.FormatInt(last.seq, 10)
	}
	if betweenListSteps != nil {
		betweenListSteps()
	}
	if p.Items, err = s.rowsBySeq(keys); err != nil {
		return Page{}, err
	}
	return p, nil
}

// betweenListSteps, when set, runs between the two reads of ListPage. Tests
// only.
var betweenListSteps func()

// pageSQL is the first step of ListPage: the (state_at, seq) of up to limit
// rows matching f, in listing order, read from an index (listIndex).
func (f ListFilter) pageSQL(limit int) (string, []any, error) {
	where, args, err := f.where()
	if err != nil {
		return "", nil, err
	}
	return `SELECT state_at, seq FROM interaction` + f.listIndex() + where + ` ORDER BY state_at DESC, seq DESC LIMIT ?`,
		append(args, limit), nil
}

// countSQL is Count's query, read from the index as pageSQL is.
func (f ListFilter) countSQL() (string, []any, error) {
	f.Cursor = ""
	where, args, err := f.where()
	if err != nil {
		return "", nil, err
	}
	return `SELECT COUNT(*) FROM interaction` + f.listIndex() + where, args, nil
}

// listIndex pins a listing to an index, because left to itself SQLite
// takes the role or peer index for the equality and then reads each
// matching row — past its long columns — to filter and sort it. A context
// filter reads idx_ix_context: a context holds a handful of tasks, and the
// covering index would be read whole to find them. A listing of one peer
// reads idx_ix_peer_list, and any other idx_ix_list: both cover everything
// a filter tests but receipt and hold the listing order, the first within
// the peer's own tasks.
func (f ListFilter) listIndex() string {
	switch {
	case f.ContextID != "":
		return ` INDEXED BY idx_ix_context`
	case f.PeerAID != "":
		return ` INDEXED BY idx_ix_peer_list`
	}
	return ` INDEXED BY idx_ix_list`
}

// pageKey is a row of a page as the first step of ListPage reads it.
type pageKey struct{ at, seq int64 }

// pageKeys runs pageSQL's query.
func (s *Store) pageKeys(q string, args []any) ([]pageKey, error) {
	rows, err := s.db.Query(q, args...)
	if err != nil {
		return nil, err
	}
	var keys []pageKey
	for rows.Next() {
		var k pageKey
		if err := rows.Scan(&k.at, &k.seq); err != nil {
			rows.Close()
			return nil, err
		}
		keys = append(keys, k)
	}
	if err := rows.Close(); err != nil {
		return nil, err
	}
	if err := rows.Err(); err != nil {
		return nil, err
	}
	return keys, nil
}

// rowsBySeq reads the rows keys name, in their order.
func (s *Store) rowsBySeq(keys []pageKey) ([]*Interaction, error) {
	if len(keys) == 0 {
		return nil, nil
	}
	ph := make([]string, len(keys))
	in := make([]any, len(keys))
	for i, k := range keys {
		ph[i], in[i] = "?", k.seq
	}
	items, err := s.query(`SELECT `+ixColumns+` FROM interaction WHERE seq IN (`+strings.Join(ph, ",")+`)`, in...)
	if err != nil {
		return nil, err
	}
	bySeq := make(map[int64]*Interaction, len(items))
	for _, ix := range items {
		bySeq[ix.Seq] = ix
	}
	out := make([]*Interaction, 0, len(keys))
	for _, k := range keys {
		if ix := bySeq[k.seq]; ix != nil { // gone between the two reads: left out
			out = append(out, ix)
		}
	}
	return out, nil
}

// ListAll returns every interaction matching f, most recent state change
// first, by walking ListPage. The filter's Cursor and Limit are ignored.
func (s *Store) ListAll(f ListFilter) ([]*Interaction, error) {
	f.Cursor, f.Limit = "", 1000
	var out []*Interaction
	for {
		p, err := s.ListPage(f)
		if err != nil {
			return nil, err
		}
		out = append(out, p.Items...)
		if p.Next == "" {
			return out, nil
		}
		f.Cursor = p.Next
	}
}

