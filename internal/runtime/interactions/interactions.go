// ErrBadCursor is returned for a cursor ListPage did not produce.
var ErrBadCursor = errors.New("interactions: invalid page cursor")

func parseCursor(c string) (at, seq int64, err error) {
	a, b, ok := strings.Cut(c, ".")
	if !ok {
		return 0, 0, ErrBadCursor
	}
	if at, err = strconv.ParseInt(a, 10, 64); err != nil {
		return 0, 0, ErrBadCursor
	}
	if seq, err = strconv.ParseInt(b, 10, 64); err != nil {
		return 0, 0, ErrBadCursor
	}
	return at, seq, nil
}

func (s *Store) query(q string, args ...any) ([]*Interaction, error) {
	rows, err := s.db.Query(q, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []*Interaction
	for rows.Next() {
		ix, err := scanRows(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, ix)
	}
	return out, rows.Err()
}

type scanner interface{ Scan(dest ...any) error }

func scanOne(row scanner) (*Interaction, error) {
	ix, err := scanRows(row)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, ErrNotFound
	}
	return ix, err
}

func scanRows(sc scanner) (*Interaction, error) {
	ix := &Interaction{}
	var role, state, verified, authIDs string
	var capFlag int
	if err := sc.Scan(&ix.Seq, &ix.ID, &role, &ix.PeerAID, &ix.Goal, &state, &ix.StateAt, &ix.StateSeq,
		&ix.RequestCID, &ix.RequestDoc, &ix.ResultCID, &ix.Result, &ix.Receipt, &ix.Review,
		&verified, &ix.EndReqBy, &ix.EndAccBy, &ix.ContextID, &ix.Trust, &capFlag, &ix.TaskNonce,
		&ix.PayState, &ix.PayRequired, &authIDs, &ix.PayPayload, &ix.PayReceipts, &ix.QuoteExpiresAt,
		&ix.PeerKEL, &ix.PeerKeys, &ix.ResultMeta, &ix.CreatedAt, &ix.UpdatedAt); err != nil {
		return nil, err
	}
	ix.Role = Role(role)
	ix.State = State(state)
	ix.ReceiptVerified = Verification(verified)
	ix.IsCapability = capFlag != 0
	if authIDs != "" {
		_ = json.Unmarshal([]byte(authIDs), &ix.PayAuthIDs)
	}
	return ix, nil
}
